/**
 * Fine Master stores ONE "due day" per college (1-31). The value lives in the
 * legacy `College.dueDate` DateTime column, but only its day component is
 * meaningful. New values are written as a UTC date in a fixed canonical month
 * (2000-01) so the day can never shift because of the server's timezone.
 *
 * Fine is charged per billing month: a fee for a given month is due on that
 * month's configured day, and overdue counting starts the following day.
 */

export type DueDateValue = Date | string | null | undefined;

export interface FineBasisFee {
  billingMonth?: string | null;
  dueDate?: DueDateValue;
  createdAt?: DueDateValue;
  /** One-off payment date for an already-completed fee row. */
  paidDate?: DueDateValue;
  status?: string | null;
  amount?: number | string | null;
  /**
   * Date after which this fee stops accruing fine (e.g. the payment that
   * settled an outstanding balance). `null`/omitted means still accruing.
   */
  fineThrough?: DueDateValue | null;
}

export interface FinePayment {
  amount?: number | string | null;
  paidDate?: DueDateValue;
  createdAt?: DueDateValue;
}

export interface FineBasisConfig {
  collegeDueDate: DueDateValue;
  billingCycle?: string | null;
}

export interface FinePeriod {
  key: string;
  dueDate: Date;
  days: number;
}

const DAY_MS = 86_400_000;
const pad2 = (value: number) => String(value).padStart(2, '0');

export const formatDateInput = (date: Date) =>
  `${date.getFullYear()}-${pad2(date.getMonth() + 1)}-${pad2(date.getDate())}`;

/** Read the configured day of month from a stored due date. */
export function getFineDueDay(value: DueDateValue): number | null {
  if (value === null || value === undefined || value === '') return null;

  const date = value instanceof Date ? new Date(value.getTime()) : new Date(value);
  if (Number.isNaN(date.getTime())) return null;

  // ISO date strings (and values coming back from Prisma) are UTC midnight.
  // Locally constructed Dates are read with local getters.
  const useUtc = !(value instanceof Date) || date.getUTCHours() === 0;
  const day = useUtc ? date.getUTCDate() : date.getDate();
  return day >= 1 && day <= 31 ? day : null;
}

/** Normalise a day-of-month (or legacy date string) into the canonical date. */
export function toCanonicalDueDate(day: number | string | null | undefined): string | null {
  if (day === null || day === undefined || String(day).trim() === '') return null;

  const raw = String(day).trim();
  const numeric = /^\d{1,2}$/.test(raw) ? Number(raw) : getFineDueDay(raw);
  if (numeric === null || !Number.isFinite(numeric)) return null;

  const clamped = Math.min(31, Math.max(1, Math.trunc(numeric)));
  return new Date(Date.UTC(2000, 0, clamped)).toISOString();
}

/** Due date for the configured day inside a specific month (clamped for short months). */
export function getMonthlyDueDate(day: number, year: number, monthIndex: number): Date {
  const lastDay = new Date(year, monthIndex + 1, 0).getDate();
  return new Date(year, monthIndex, Math.min(day, lastDay));
}

function startOfDay(value: DueDateValue): Date | null {
  if (value === null || value === undefined || value === '') return null;
  const date = value instanceof Date ? new Date(value.getTime()) : new Date(value);
  if (Number.isNaN(date.getTime())) return null;
  date.setHours(0, 0, 0, 0);
  return date;
}

function daysBetween(due: Date, asOf: Date): number {
  if (asOf.getTime() <= due.getTime()) return 0;
  return Math.floor((asOf.getTime() - due.getTime()) / DAY_MS);
}

/**
 * Which month a fee's due date belongs to.
 *
 * - Fees generated by the monthly cron carry `billingMonth` (YYYY-MM). For
 *   POSTPAID colleges the invoice is raised in the following month, so that is
 *   when it becomes due.
 * - Older EB/outstanding fees only have their own due date or creation date,
 *   i.e. the month in which the bill was raised.
 */
function resolveDueMonth(
  fee: FineBasisFee,
  config: FineBasisConfig,
  asOf: Date,
): { year: number; monthIndex: number } {
  const billing = /^(\d{4})-(\d{1,2})$/.exec(String(fee.billingMonth || '').trim());
  if (billing) {
    let year = Number(billing[1]);
    let monthIndex = Number(billing[2]) - 1;
    if (String(config.billingCycle || '').toUpperCase() === 'POSTPAID') {
      const next = new Date(year, monthIndex + 1, 1);
      year = next.getFullYear();
      monthIndex = next.getMonth();
    }
    return { year, monthIndex };
  }

  for (const candidate of [fee.dueDate, fee.createdAt]) {
    const date = startOfDay(candidate);
    if (date) return { year: date.getFullYear(), monthIndex: date.getMonth() };
  }

  // Synthetic/legacy rows without any date information fall back to the
  // stored date itself (a real date, not the canonical 2000 placeholder).
  const legacy = startOfDay(config.collegeDueDate);
  if (legacy && legacy.getFullYear() > 2001) {
    return { year: legacy.getFullYear(), monthIndex: legacy.getMonth() };
  }
  return { year: asOf.getFullYear(), monthIndex: asOf.getMonth() };
}

/**
 * Build one overdue period per due month for the supplied fees. Multiple fees
 * of the same type in the same month share a single due date, so they are
 * charged once.
 */
export function getFinePeriods(
  fees: FineBasisFee[],
  config: FineBasisConfig,
  asOf: Date,
): FinePeriod[] {
  const day = getFineDueDay(config.collegeDueDate);
  if (day === null) return [];

  const asOfStart = startOfDay(asOf);
  if (!asOfStart) return [];

  const periods = new Map<string, FinePeriod>();
  for (const fee of fees || []) {
    const { year, monthIndex } = resolveDueMonth(fee, config, asOfStart);
    const key = `${year}-${pad2(monthIndex + 1)}`;
    const dueDate = getMonthlyDueDate(day, year, monthIndex);

    // A fee that has been paid stops accruing on its payment date. Multiple
    // fees in one month share a single fine, charged for the longest period
    // any of them remained unpaid.
    const settled = fee.fineThrough ? startOfDay(fee.fineThrough) : null;
    const effectiveAsOf =
      settled && settled.getTime() < asOfStart.getTime() ? settled : asOfStart;
    const days = daysBetween(dueDate, effectiveAsOf);
    const existing = periods.get(key);
    if (!existing) {
      periods.set(key, { key, dueDate, days });
    } else if (days > existing.days) {
      existing.days = days;
    }
  }
  return Array.from(periods.values());
}

export const sumFineDays = (periods: FinePeriod[]) =>
  periods.reduce((total, period) => total + period.days, 0);

const MONEY_EPSILON = 0.001;
const money = (value: number) => Math.round(value * 100) / 100;

const feeTime = (fee: FineBasisFee) =>
  startOfDay(fee.paidDate ?? fee.createdAt ?? fee.dueDate)?.getTime() ?? 0;

/**
 * Work out when each fee stops accruing fine.
 *
 * - Completed fee rows accrue only up to their own `paidDate`, so paying on
 *   or before the due day produces zero days and a late payment does not
 *   keep growing afterwards.
 * - Outstanding invoices stay PENDING and are settled by separate completed
 *   payment rows. Payments are allocated oldest-first; the date of the
 *   payment that clears an invoice is its fine cut-off. A `null` result means
 *   a balance is still outstanding and the fine keeps accruing.
 */
export function resolveFineThrough(
  fees: FineBasisFee[],
  payments: FinePayment[],
): Array<Date | null> {
  const result: Array<Date | null> = fees.map((fee) => {
    if (String(fee.status || '').toUpperCase() !== 'COMPLETED') return null;
    // A completed fee with no recorded payment date is already settled; use a
    // sentinel far in the past so it can never accrue a retrospective fine.
    return startOfDay(fee.paidDate ?? fee.createdAt) ?? new Date(0);
  });

  const obligations = fees
    .map((fee, index) => ({
      fee,
      index,
      remaining: Math.max(0, Number(fee.amount) || 0),
    }))
    .filter(
      (item) =>
        String(item.fee.status || '').toUpperCase() !== 'COMPLETED' &&
        item.remaining > MONEY_EPSILON,
    )
    .sort((a, b) => feeTime(a.fee) - feeTime(b.fee));

  const sortedPayments = payments
    .map((payment) => ({
      date: startOfDay(payment.paidDate ?? payment.createdAt),
      amount: Number(payment.amount) || 0,
    }))
    .filter((payment) => payment.date && payment.amount > MONEY_EPSILON)
    .sort((a, b) => a.date!.getTime() - b.date!.getTime());

  let paymentIndex = 0;
  let appliedInPayment = 0;

  for (const obligation of obligations) {
    let remaining = money(obligation.remaining);

    while (remaining > MONEY_EPSILON && paymentIndex < sortedPayments.length) {
      const payment = sortedPayments[paymentIndex];
      const available = money(payment.amount - appliedInPayment);
      if (available <= MONEY_EPSILON) {
        paymentIndex += 1;
        appliedInPayment = 0;
        continue;
      }

      const used = money(Math.min(remaining, available));
      remaining = money(remaining - used);
      appliedInPayment = money(appliedInPayment + used);

      if (remaining <= MONEY_EPSILON && payment.date) {
        result[obligation.index] = payment.date;
      }
      if (appliedInPayment >= payment.amount - MONEY_EPSILON) {
        paymentIndex += 1;
        appliedInPayment = 0;
      }
    }

    if (remaining > MONEY_EPSILON) result[obligation.index] = null;
  }

  return result;
}

/** The most recent due date in the set (used for display in the pay modal). */
export function latestDueDate(periods: FinePeriod[]): Date | null {
  return periods.reduce<Date | null>((latest, period) => {
    if (!latest || period.dueDate.getTime() > latest.getTime()) return period.dueDate;
    return latest;
  }, null);
}
